let language = 'es';
try {
  const savedLanguage = localStorage.getItem('enruta-language');
  if (savedLanguage === 'es' || savedLanguage === 'en') language = savedLanguage;
} catch { /* Storage may be disabled. */ }

document.documentElement.lang = language;

export function t(key, values = {}) {
  const text = language === 'en' ? (english[key] || key) : key;
  return text.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? `{${name}}`));
}

export function getLanguage() {
  return language;
}

export function getLocale() {
  return language === 'en' ? 'en-GB' : 'es';
}

export function setLanguage(nextLanguage) {
  if (nextLanguage !== 'es' && nextLanguage !== 'en') throw new Error(`Unsupported language: ${nextLanguage}`);
  language = nextLanguage;
  document.documentElement.lang = language;
  try { localStorage.setItem('enruta-language', language); } catch { /* Storage may be disabled. */ }
}

export function applyDocumentTranslations(root = document) {
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  for (const element of root.querySelectorAll('[data-i18n-html]')) element.innerHTML = t(element.dataset.i18nHtml);
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  for (const element of root.querySelectorAll('[data-i18n-content]')) element.setAttribute('content', t(element.dataset.i18nContent));
  for (const element of root.querySelectorAll('[data-i18n-aria-label]')) element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  for (const element of root.querySelectorAll('[data-i18n-title]')) element.setAttribute('title', t(element.dataset.i18nTitle));
}
